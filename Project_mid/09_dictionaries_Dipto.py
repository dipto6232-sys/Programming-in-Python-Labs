
PRODUCT_CATEGORY = {
    "Laptop": "Electronics",
    "Smartphone": "Electronics",
    "Headphones": "Electronics",
    "Desk": "Furniture",
    "Office Chair": "Furniture",
    "Blender": "Appliances",
    "Coffee Maker": "Appliances",
    "Notebook": "Stationery",
    "Printer Paper": "Stationery",
    "Water Bottle": "Accessories"
}

order_tuples = [
    ("ORD-00742", "Laptop", "Khulna", 3, 1104.24, 0.0),
    ("ORD-00879", "Headphones", "Sylhet", 1, 144.83, 0.1),
    ("ORD-00059", "Desk", "Sylhet", 5, 207.13, 0.0),
    ("ORD-00628", "Office Chair", "Sylhet", 1, 168.07, 0.1),
    ("ORD-00874", "Laptop", "Sylhet", 8, 962.66, 0.0),
    ("ORD-00594", "Smartphone", "Barishal", 6, 269.73, 0.1),
    ("ORD-00145", "Printer Paper", "Dhaka", 4, 11.74, 0.05),
    ("ORD-00607", "Blender", "Khulna", 8, 123.69, 0.0)
]


print("\n1. Individual Sales Record")
print("Storing complete information about one sale using a dictionary.")

sale = {
    "Order_ID": "ORD-00742",
    "Product": "Laptop",
    "Region": "Khulna",
    "Units_Sold": 3,
    "Unit_Price_BDT": 1104.24,
    "Discount_Rate": 0.0
}

sale["Revenue_BDT"] = round(
    sale["Units_Sold"] * sale["Unit_Price_BDT"] *
    (1 - sale["Discount_Rate"]), 2
)

print("Product:", sale["Product"])
print("Revenue:", sale["Revenue_BDT"], "BDT")

sale["Units_Sold"] = 4
sale["Revenue_BDT"] = round(
    sale["Units_Sold"] * sale["Unit_Price_BDT"] *
    (1 - sale["Discount_Rate"]), 2
)

print("Updated quantity:", sale["Units_Sold"])
print("Updated revenue:", sale["Revenue_BDT"], "BDT")
sale["Status"] = "Completed"
print("Order status:", sale["Status"])


print("\n2. Product Category Management")
print("Finding the category of each product using a dictionary lookup.")

print("Laptop category:", PRODUCT_CATEGORY["Laptop"])
print("Blender category:", PRODUCT_CATEGORY["Blender"])
print("Total registered products:", len(PRODUCT_CATEGORY))


print("\n3. Converting Sales Records into Dictionaries")
print("Organizing sales information into dictionaries for easier business analysis.")

orders = []

for order_id, product, region, units, unit_price, discount_rate in order_tuples:
    order = {
        "Order_ID": order_id,
        "Product": product,
        "Category": PRODUCT_CATEGORY[product],
        "Region": region,
        "Units_Sold": units,
        "Revenue_BDT": round(
            units * unit_price * (1 - discount_rate), 2
        )
    }

    orders.append(order)

print("Total sales records:", len(orders))
print("First order:", orders[0])


print("\n4. Order Search by Order ID")
print("Enter an Order ID to find its sales information.")

order_index = {}

for order in orders:
    order_index[order["Order_ID"]] = order

search_id = input("Enter Order ID (e.g. ORD-00874): ").strip().upper()

if search_id in order_index:
    found_order = order_index[search_id]

    print("\nOrder Found!")
    print("Product:", found_order["Product"])
    print("Category:", found_order["Category"])
    print("Region:", found_order["Region"])
    print("Units sold:", found_order["Units_Sold"])
    print(f"Revenue: {found_order['Revenue_BDT']:,.2f} BDT")
else:
    print("Order ID not found in the sales records.")


print("\n5. Revenue Analysis by Region")
print("Calculating total revenue generated by each sales region.")

region_revenue = {}

for order in orders:
    region = order["Region"]

    region_revenue[region] = round(
        region_revenue.get(region, 0) + order["Revenue_BDT"], 2
    )

for region, revenue in region_revenue.items():
    print(f"{region:<10} {revenue:>10,.2f} BDT")


print("\n6. Product Order Count")
print("Counting how many orders each product received.")

product_count = {}

for order in orders:
    product = order["Product"]

    product_count[product] = product_count.get(product, 0) + 1

for product, count in product_count.items():
    print(f"{product:<15} {count} orders")


print("\n7. Top Performing Region")
print("Identifying the region that generated the highest revenue.")

top_region = max(region_revenue, key=region_revenue.get)

print("Top region:", top_region)
print(f"Total revenue: {region_revenue[top_region]:,.2f} BDT")


print("\n8. Regional Business Summary")
print("Combining order counts and revenue into a nested dictionary.")

region_summary = {}

for order in orders:
    region = order["Region"]

    if region not in region_summary:
        region_summary[region] = {
            "orders": 0,
            "revenue": 0.0
        }

    region_summary[region]["orders"] += 1
    region_summary[region]["revenue"] += order["Revenue_BDT"]

for region, summary in region_summary.items():
    print(
        f"{region:<10} "
        f"Orders: {summary['orders']}  "
        f"Revenue: {summary['revenue']:,.2f} BDT"
    )
